from __future__ import annotations

from dataclasses import dataclass
from typing import Any

import cv2
import numpy as np

from .material_profiles import canonical_material_mode


IDENTITY_STATUSES = {
    "unknown",
    "confirmed_absent",
    "detected",
    "unavailable",
    "failed",
}
RERENDER_POLICIES = {"auto", "never", "transparent_optical", "regional"}

_CLEAR_VESSEL_TOKENS = (
    "pitcher", "carafe", "jug", "decanter", "tumbler", "drinking_glass",
    "glass_cup", "glass_vase", "clear_vessel",
)
_IDENTITY_LIKELY_TOKENS = (
    "bottle", "can", "package", "packaging", "label", "branded", "printed",
    "book", "box", "carton", "cosmetic", "electronics", "food", "beverage",
)


@dataclass(frozen=True)
class IdentityMaskBundle:
    hard_restore_mask: np.ndarray
    structure_guard_mask: np.ndarray
    rerender_allow_mask: np.ndarray
    route: str
    has_identity: bool | None
    provenance: dict[str, Any]


def validate_identity_status(value: str) -> str:
    status = str(value or "unknown").strip().lower()
    if status not in IDENTITY_STATUSES:
        raise ValueError(f"identity_status must be one of {sorted(IDENTITY_STATUSES)}")
    return status


def validate_rerender_policy(value: str) -> str:
    policy = str(value or "auto").strip().lower()
    if policy not in RERENDER_POLICIES:
        raise ValueError(f"rerender_policy must be one of {sorted(RERENDER_POLICIES)}")
    return policy


def warp_identity_mask(
    source_mask: np.ndarray,
    homography: np.ndarray,
    shape: tuple[int, int],
    placed_alpha: np.ndarray,
) -> np.ndarray:
    """Warp identity evidence with the exact product transform.

    Identity evidence is conservative: nearest-neighbour sampling avoids
    erasing a one-pixel glyph stroke, and a one-pixel dilation protects the
    antialiased transition generated by the product's Lanczos warp.
    """
    if source_mask.ndim != 2:
        raise ValueError("identity mask must be a single-channel image")
    if source_mask.dtype == np.bool_:
        source = source_mask.astype(np.uint8) * 255
    else:
        source = np.clip(source_mask, 0, 255).astype(np.uint8)
    height, width = shape
    warped = cv2.warpPerspective(
        source,
        np.asarray(homography, np.float64),
        (width, height),
        flags=cv2.INTER_NEAREST,
        borderMode=cv2.BORDER_CONSTANT,
    )
    if np.any(warped):
        warped = cv2.dilate(warped, np.ones((3, 3), np.uint8), iterations=1)
    warped[placed_alpha <= 4] = 0
    return warped


def _structure_guard(
    alpha: np.ndarray,
    *,
    radius_cap: int = 7,
) -> np.ndarray:
    active = (alpha > 4).astype(np.uint8)
    if not np.any(active):
        return np.zeros_like(active, dtype=bool)
    points = np.argwhere(active)
    y0, x0 = points.min(axis=0)
    y1, x1 = points.max(axis=0)
    short_extent = max(1, min(int(y1 - y0 + 1), int(x1 - x0 + 1)))
    radius = int(np.clip(round(short_extent * 0.012), 2, radius_cap))
    kernel = np.ones((radius * 2 + 1, radius * 2 + 1), np.uint8)
    # Erosion protects the outer silhouette and every alpha hole (handles,
    # stems and cut-outs) without pretending that old-room RGB is identity.
    interior = cv2.erode(active, kernel, iterations=1).astype(bool)
    return active.astype(bool) & ~interior


def _clear_vessel_base_guard(alpha: np.ndarray) -> np.ndarray:
    """Protect the thick foot of a clear catalogue vessel from generation.

    Generative relighting is useful through the broad optical body, but the
    lowest glass band carries the contact line, foot thickness and silhouette
    closure.  Allowing a model to repaint that band repeatedly produced
    ice/shard/foam-like structures.  Keep it deterministic while leaving the
    upper body, spout and handle interior available for scene-conditioned
    reconstruction.
    """
    active = np.asarray(alpha) > 4
    if not np.any(active):
        return np.zeros_like(active)
    ys = np.flatnonzero(np.any(active, axis=1))
    if ys.size < 3:
        return active.copy()
    top, bottom = int(ys[0]), int(ys[-1])
    # Lock only the foot closure/contact band.  The optically broad lower body
    # still needs scene-aware reconstruction; guarding the lowest fifth left
    # displaced tabletop hardware visibly trapped inside the pitcher.
    start = top + int(round((bottom - top + 1) * 0.94))
    rows = np.arange(active.shape[0])[:, None]
    return active & (rows >= start)


def _semantic_route(
    material_mode: str,
    semantic_category: str,
    physical_type: str,
) -> tuple[bool, str]:
    mode = canonical_material_mode(material_mode)
    text = f"{semantic_category} {physical_type}".strip().lower()
    if any(token in text for token in _IDENTITY_LIKELY_TOKENS):
        return False, "semantic_identity_likely"
    if mode == "clear_glass" and any(token in text for token in _CLEAR_VESSEL_TOKENS):
        return True, "semantic_unlabelled_clear_vessel"
    return False, "semantic_evidence_insufficient"


def conservative_source_identity_mask(
    source_rgba: np.ndarray,
    *,
    material_mode: str,
    semantic_category: str = "",
    physical_type: str = "",
) -> tuple[np.ndarray | None, str]:
    """Build a material-first identity mask in source coordinates.

    OCR is evidence, not the router.  Opaque goods stay byte-for-byte strict.
    A mixed transparent bottle is partitioned: label/cap/product-colour pixels
    stay strict while label-free glass can receive scene-dependent optics.
    An unlabelled clear vessel has no source-RGB identity region, so its full
    optical interior remains eligible for reconstruction/rerendering.
    """
    rgba = np.asarray(source_rgba)
    if rgba.ndim != 3 or rgba.shape[2] != 4:
        raise ValueError("source RGBA must have shape HxWx4")
    alpha = rgba[..., 3]
    mode = canonical_material_mode(material_mode)
    semantic_allow, reason = _semantic_route(
        mode, semantic_category, physical_type,
    )
    if semantic_allow or reason != "semantic_identity_likely":
        return None, reason

    transmissive = mode in {
        "clear_glass", "frosted_glass", "colored_glass", "mixed_transparent",
    }
    if transmissive:
        mask = _mixed_transparent_identity_regions(rgba)
        if np.any(mask):
            return mask, "material_partition_identity_guard_v2"
        # A branded transmissive object with no stable regional evidence is
        # safer as strict than silently allowing a model to rewrite identity.
        strict = np.zeros(alpha.shape, np.uint8)
        strict[alpha > 4] = 255
        return strict, "material_partition_failed_full_guard_v2"

    mask = np.zeros(alpha.shape, np.uint8)
    mask[alpha > 4] = 255
    return mask, "opaque_full_silhouette_identity_guard_v2"


def _mixed_transparent_identity_regions(source_rgba: np.ndarray) -> np.ndarray:
    """Conservatively isolate labels, closures, liquid and printed regions.

    This deliberately does not try to *read* text.  It combines a bottle
    geometry prior with material evidence (dark ink/label, chroma/liquid and
    high-frequency print).  The enclosing label rectangle is filled so bright
    glyph interiors cannot fall through merely because OCR missed them.
    """
    rgba = np.asarray(source_rgba)
    alpha = rgba[..., 3]
    body = alpha > 4
    out = np.zeros(alpha.shape, np.uint8)
    if not np.any(body):
        return out
    ys, xs = np.where(body)
    y0, y1 = int(ys.min()), int(ys.max()) + 1
    x0, x1 = int(xs.min()), int(xs.max()) + 1
    h, w = y1 - y0, x1 - x0
    if h < 8 or w < 8:
        out[body] = 255
        return out

    rgb = rgba[..., :3].astype(np.float32)
    luma = 0.2126 * rgb[..., 0] + 0.7152 * rgb[..., 1] + 0.0722 * rgb[..., 2]
    chroma = rgb.max(axis=2) - rgb.min(axis=2)
    active_luma = luma[body]
    active_chroma = chroma[body]
    dark_cut = float(np.percentile(active_luma, 38.0))
    chroma_cut = max(18.0, float(np.percentile(active_chroma, 58.0)))

    # Cap/closure is product identity even when it carries no readable text.
    cap_bottom = y0 + max(2, int(round(h * 0.15)))
    cap = body.copy()
    cap[cap_bottom:, :] = False

    yy, xx = np.indices(alpha.shape)
    xn = (xx - x0) / max(1.0, float(w - 1))
    yn = (yy - y0) / max(1.0, float(h - 1))
    front_body = body & (xn >= 0.08) & (xn <= 0.92) & (yn >= 0.25) & (yn <= 0.90)

    gray = np.clip(luma, 0, 255).astype(np.uint8)
    grad_x = cv2.Sobel(gray, cv2.CV_32F, 1, 0, ksize=3)
    grad_y = cv2.Sobel(gray, cv2.CV_32F, 0, 1, ksize=3)
    detail = cv2.magnitude(grad_x, grad_y)
    detail_cut = max(20.0, float(np.percentile(detail[body], 72.0)))
    seeds = front_body & (
        (luma <= dark_cut) | (chroma >= chroma_cut) | (detail >= detail_cut)
    )
    seeds_u8 = seeds.astype(np.uint8)
    close_w = max(3, (int(round(w * 0.035)) | 1))
    close_h = max(3, (int(round(h * 0.020)) | 1))
    seeds_u8 = cv2.morphologyEx(
        seeds_u8,
        cv2.MORPH_CLOSE,
        cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (close_w, close_h)),
        iterations=2,
    )

    # Keep material/print components, then protect each complete enclosing
    # label region so white glyphs and small punctuation remain source pixels.
    count, labels, stats, _ = cv2.connectedComponentsWithStats(seeds_u8, 8)
    min_area = max(12, int(round(h * w * 0.0008)))
    regions = np.zeros_like(body)
    for idx in range(1, count):
        sx, sy, sw, sh, area = (int(v) for v in stats[idx])
        if area < min_area:
            continue
        if sw < max(2, int(w * 0.03)) and sh < max(2, int(h * 0.025)):
            continue
        pad_x = max(2, int(round(sw * 0.06)))
        pad_y = max(2, int(round(sh * 0.05)))
        rx0, rx1 = max(x0, sx - pad_x), min(x1, sx + sw + pad_x)
        ry0, ry1 = max(y0, sy - pad_y), min(y1, sy + sh + pad_y)
        regions[ry0:ry1, rx0:rx1] = True

    # Coloured contents are part of the sold product, not old-room light.
    product_colour = (
        body
        & (chroma >= chroma_cut)
        & (yn >= 0.12)
        & (yn <= 0.74)
        & (xn >= 0.24)
        & (xn <= 0.76)
        & ~regions
    )
    identity = body & (cap | regions | product_colour)
    if np.any(identity):
        radius = max(1, int(round(min(h, w) * 0.006)))
        kernel = cv2.getStructuringElement(
            cv2.MORPH_ELLIPSE, (radius * 2 + 1, radius * 2 + 1),
        )
        identity = cv2.dilate(identity.astype(np.uint8), kernel, iterations=1) > 0
        identity &= body
    out[identity] = 255
    return out


def build_identity_masks(
    placed_alpha: np.ndarray,
    *,
    material_mode: str,
    semantic_category: str = "",
    physical_type: str = "",
    identity_status: str = "unknown",
    rerender_policy: str = "auto",
    placed_identity_mask: np.ndarray | None = None,
) -> IdentityMaskBundle:
    """Build hard identity and generative authorization masks.

    V1 deliberately treats unknown/detected packaged goods as entirely strict.
    A clear, unlabelled vessel may expose only its *interior* to a generated
    optical candidate.  The data model already supports regional masks, so a
    later OCR/logo detector can open label-free glass without changing the
    recovery contract.
    """
    if placed_alpha.ndim != 2:
        raise ValueError("placed alpha must be a single-channel image")
    status = validate_identity_status(identity_status)
    policy = validate_rerender_policy(rerender_policy)
    mode = canonical_material_mode(material_mode)
    body = placed_alpha > 4
    explicit = (
        np.zeros_like(body)
        if placed_identity_mask is None
        else np.asarray(placed_identity_mask) > 0
    )
    if explicit.shape != body.shape:
        raise ValueError("placed identity mask must match placed alpha")
    explicit &= body
    # Unlabelled clear glass derives its photographic identity from inner-rim,
    # handle and thick-wall highlights.  Guarding the same 6--7 px band used
    # for opaque products removed exactly those scene-conditioned cues from a
    # valid optical rerender and left a flat transparent decal.  Keep a strict
    # two-pixel silhouette invariant for clear glass; all opaque and branded
    # routes retain the wider conservative guard.
    structure = _structure_guard(
        placed_alpha,
        radius_cap=2 if mode == "clear_glass" else 7,
    )
    base_structure = np.zeros_like(structure)
    if mode == "clear_glass":
        base_structure = _clear_vessel_base_guard(placed_alpha)
        structure |= base_structure

    has_identity: bool | None
    if status == "detected" or np.any(explicit):
        has_identity = True
    elif status == "confirmed_absent":
        has_identity = False
    else:
        has_identity = None

    semantic_allow, semantic_reason = _semantic_route(
        mode, semantic_category, physical_type,
    )
    allow_regional = False
    reason = "strict_by_policy"
    if policy == "never":
        reason = "rerender_policy_never"
    elif status in {"unavailable", "failed"}:
        reason = f"identity_analysis_{status}"
    elif policy == "transparent_optical":
        allow_regional = mode == "clear_glass" and has_identity is not True
        reason = "explicit_transparent_optical" if allow_regional else "transparent_policy_not_safe"
    elif policy == "regional":
        transmissive = mode in {
            "clear_glass", "frosted_glass", "colored_glass", "mixed_transparent",
        }
        # Fail closed: a caller claiming detected identity must provide the
        # non-empty pixel evidence that will be restored after generation.
        if status == "detected" and not np.any(explicit):
            allow_regional = False
            reason = "regional_identity_mask_missing"
        else:
            allow_regional = transmissive and np.any(explicit)
            reason = (
                "explicit_regional_mask"
                if allow_regional
                else "regional_requires_transmissive_material_and_mask"
            )
    elif status == "confirmed_absent" and mode == "clear_glass":
        allow_regional = True
        reason = "confirmed_no_identity_clear_glass"
    elif np.any(explicit) and mode in {
        "clear_glass", "frosted_glass", "colored_glass", "mixed_transparent",
    }:
        # Auto-generated material partitions are hard identity evidence, not
        # a reason to lock the entire transparent object.  Only the remaining
        # optical interior is authorized for a candidate model.
        allow_regional = True
        reason = "material_partition_with_identity_guard"
    elif status == "unknown" and semantic_allow:
        # This is the requested coarse first release.  It is intentionally
        # limited to clear vessel categories; bottles/cans/packages never take
        # this shortcut.  The provenance makes the assumption visible.
        allow_regional = True
        reason = semantic_reason
    else:
        reason = semantic_reason

    if allow_regional:
        hard = explicit.copy()
        allow = body & ~structure & ~hard
        route = "regional_rerender"
    else:
        hard = body.copy()
        allow = np.zeros_like(body)
        route = "strict_product"

    return IdentityMaskBundle(
        hard_restore_mask=hard,
        structure_guard_mask=structure,
        rerender_allow_mask=allow,
        route=route,
        has_identity=has_identity,
        provenance={
            "schema_version": "product-identity-v2",
            "identity_status": status,
            "rerender_policy": policy,
            "material_mode": mode,
            "semantic_category": semantic_category,
            "physical_type": physical_type,
            "route_reason": reason,
            "identity_detection": (
                "explicit_mask" if np.any(explicit) else "semantic_conservative_v1"
            ),
            "hard_restore_pixels": int(np.count_nonzero(hard)),
            "structure_guard_pixels": int(np.count_nonzero(structure)),
            "base_structure_guard_pixels": int(np.count_nonzero(base_structure)),
            "rerender_allowed_pixels": int(np.count_nonzero(allow)),
        },
    )
